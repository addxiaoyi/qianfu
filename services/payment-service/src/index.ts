/**
 * Payment Service - 主入口
 * 独立的支付处理微服务
 */

import { createApp } from './app.js';

// ============================================================================
// 应用初始化
// ============================================================================

const app = createApp();

// ============================================================================
// 启动
// ============================================================================

const PORT = parseInt(process.env.PORT || '3090');

app.listen(PORT, () => {
  console.log(`Payment Service started on port ${PORT}`);
});

export default app;
